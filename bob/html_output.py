"""HTML serialization of audit results.

Produces a standalone HTML report (no external dependencies, no JavaScript).
Suitable for saving to a file, attaching to tickets, or serving from a web server.

Usage:
    from bob.html_output import build_html_output
    print(build_html_output(engine, sys_info, t))

M-4 (v0.7.2): all user-facing strings are now sourced from the translation
function ``t`` (or the hardcoded English fallback dict ``_FALLBACK_LABELS``
when ``t=None``). The ``<html lang="...">`` attribute is set from the
optional ``lang`` parameter (defaults to "en"). Same shape as
``bob/markdown_output.py``.
"""

from __future__ import annotations

from datetime import datetime, timezone
from html import escape

from bob.report import SystemInfo
from bob.scoring import FindingLevel, ScoreEngine

# M-4 (v0.7.2): translation key per level (the displayed string is
# i18n-rendered at render time). The keys here map to entries in the
# ``html_output`` namespace; the fallback dict supplies English defaults.
_LEVEL_LABEL_KEY: dict[FindingLevel, str] = {
    FindingLevel.ALERT: "html_output.level_alert",
    FindingLevel.WARN:  "html_output.level_warn",
    FindingLevel.INFO:  "html_output.level_info",
    FindingLevel.OK:    "html_output.level_ok",
}

_LEVEL_COLOR: dict[FindingLevel, str] = {
    FindingLevel.ALERT: "#dc3545",
    FindingLevel.WARN:  "#fd7e14",
    FindingLevel.INFO:  "#0d6efd",
    FindingLevel.OK:    "#198754",
}

_LEVEL_ORDER = [FindingLevel.ALERT, FindingLevel.WARN, FindingLevel.INFO, FindingLevel.OK]


