def build_html_output(
    engine: ScoreEngine,
    sys_info: SystemInfo,
    t=None,
    lang: str = "en",
) -> str:
    """Return a standalone HTML string with the full audit report.

    Args:
        engine:   The audit ScoreEngine after ``finalize()``.
        sys_info: Populated SystemInfo for the host.
        t:        Optional translation function ``t(key, **kwargs) -> str``.
                  When ``None`` (legacy / test path), an English fallback is
                  used. Production callers should pass the audit's bound
                  ``t``.
        lang:     ISO 639-1 language code emitted as the ``<html lang="">``
                  attribute. Defaults to "en" matching the English fallback.
    """
    if t is None:
        t = _fallback_t
    ts         = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    score      = engine.score
    s_color    = _score_color(score)
    # I-1 (v0.7.0 Phase 2.1): use effective_level (posture-aware) for the
    # displayed risk, matching display/JSON/CSV/webhook contracts. Fallback
    # to engine.level for legacy test mocks that don't populate the new
    # property.
    # M-12 (v0.7.3): the displayed risk label is now translated. Pre-v0.7.3
    # the summary header showed the raw English value upper-cased ("LOW",
    # "HIGH") regardless of locale, while the finding badges below were
    # already translated through _LEVEL_LABEL_KEY. Now both surfaces use
    # the same i18n contract.
    _eff_level = getattr(engine, "effective_level", engine.level)
    if _eff_level is not None:
        # Try a locale key like html_output.risk_low / risk_medium / ...;
        # fall back to the upper-cased value so unknown enum values still
        # surface something visible.
        _risk_key = f"html_output.risk_{_eff_level.value}"
        level_label = t(_risk_key)
        if level_label == _risk_key:
            level_label = str(_eff_level.value).upper()
    else:
        level_label = t("html_output.risk_unknown")

    parts: list[str] = []
    a = parts.append

    a("<!DOCTYPE html>")
    a(f'<html lang="{_h(lang)}">')
    a("<head>")
    a('<meta charset="utf-8">')
    a('<meta name="viewport" content="width=device-width,initial-scale=1">')
    a(f"<title>{_h(t('html_output.title_prefix'))} — {_h(sys_info.hostname)} — {_h(ts)}</title>")
    a(f"<style>{_CSS}</style>")
    a("</head>")
    a("<body>")

    a(f"<h1>{_h(t('html_output.report_title'))} — {_h(sys_info.hostname)}</h1>")

    # --- Summary ---
    a('<dl class="meta-grid">')
    a(f"<dt>{_h(t('html_output.field_score'))}</dt><dd>"
      f'<span class="score-circle" style="background:{_h(s_color)}">{score}</span>'
      f" / 10 &nbsp; <strong>{_h(level_label)}</strong></dd>")
    a(f"<dt>{_h(t('html_output.field_alerts'))}</dt><dd>{engine.alert_count}</dd>")
    a(f"<dt>{_h(t('html_output.field_warnings'))}</dt><dd>{engine.warn_count}</dd>")
    a(f"<dt>{_h(t('html_output.field_host'))}</dt><dd><code>{_h(sys_info.hostname)}</code></dd>")
    a(f"<dt>{_h(t('html_output.field_os'))}</dt><dd>{_h(sys_info.os_name)}</dd>")
    a(f"<dt>{_h(t('html_output.field_kernel'))}</dt><dd>{_h(sys_info.kernel)}</dd>")
    a(f"<dt>{_h(t('html_output.field_timestamp'))}</dt><dd>{_h(ts)}</dd>")
    a("</dl>")

    # --- Score deductions ---
    deductions = [d for d in engine.breakdown if d.points > 0]
    if deductions:
        a(f"<h2>{_h(t('html_output.heading_deductions'))}</h2>")
        a(f"<table><thead><tr><th>{_h(t('html_output.col_points'))}</th>"
          f"<th>{_h(t('html_output.col_reason'))}</th></tr></thead><tbody>")
        for d in deductions:
            a(f"<tr><td><strong>−{d.points}</strong></td><td>{_h(d.reason)}</td></tr>")
        a("</tbody></table>")

    # --- Findings by severity ---
    findings_by_level: dict[FindingLevel, list] = {lvl: [] for lvl in _LEVEL_ORDER}
    for f in engine.findings:
        if f.level in findings_by_level:
            findings_by_level[f.level].append(f)

    if not engine.findings:
        a(f"<p>{_h(t('html_output.no_findings'))}</p>")

    for level in _LEVEL_ORDER:
        group = findings_by_level[level]
        if not group:
            continue
        color = _LEVEL_COLOR[level]
        label = t(_LEVEL_LABEL_KEY[level])
        findings_count_str = t("html_output.findings_count", count=len(group))
        a(f'<h2><span class="badge" style="background:{_h(color)}">{_h(label)}</span>'
          f" &nbsp; {_h(findings_count_str)}</h2>")
        a(f"<table><thead><tr><th>{_h(t('html_output.col_message'))}</th>"
          f"<th>{_h(t('html_output.col_fix_command'))}</th></tr></thead><tbody>")
        for f in group:
            # v0.8.0 drift batch (Tier 9): surface note + detail in the
            # message cell so HTML/Markdown reports carry the same
            # operator-relevant context as terminal + JSON output.
            # Pre-v0.8.0, note and detail were silently dropped from
            # these reports.
            msg_html = _h(f.message or "")
            if f.detail:
                msg_html += (
                    f'<div class="finding-detail"><em>'
                    f'{_h(t("html_output.detail_label"))}: '
                    f'{_h(f.detail)}</em></div>'
                )
            if f.note:
                msg_html += (
                    f'<div class="finding-note"><em>'
                    f'{_h(t("html_output.note_label"))}: '
                    f'{_h(f.note)}</em></div>'
                )
            cmd = f"<code>{_h(f.cmd)}</code>" if f.cmd else ""
            a(f"<tr><td>{msg_html}</td><td>{cmd}</td></tr>")
        a("</tbody></table>")

    # Footer is rendered as raw HTML (contains an anchor); avoid double-escape.
    a(f"<footer>{t('html_output.footer')}</footer>")
    a("</body></html>")

    return "\n".join(parts)
